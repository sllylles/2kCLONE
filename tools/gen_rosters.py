#!/usr/bin/env python3
"""Generates data/players.json with fictional rosters for every team in data/teams.json.

The output is deterministic (fixed seed). Edit players.json directly afterwards if
you like; re-running this script overwrites it.
    python3 tools/gen_rosters.py
"""
import json, random, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
FIRST = ["Marcus", "Dorian", "Jalen", "Theo", "Isaiah", "Andre", "Malik", "Cyrus", "Elijah", "Quentin",
         "Rafael", "Tobias", "Desmond", "Kendrick", "Luca", "Mateo", "Omari", "Silas", "Xavier", "Zion",
         "Nikolai", "Bram", "Caleb", "Dante", "Emeka", "Felix", "Gideon", "Hakeem", "Ivan", "Jonah",
         "Kofi", "Leon", "Mason", "Nate", "Otis", "Pierce", "Reggie", "Sami", "Tariq", "Uriah", "Vince", "Wes"]
LAST = ["Abernathy", "Bellamy", "Castellanos", "Draper", "Okafor-Lund", "Fairweather", "Galloway", "Hollis",
        "Ivers", "Jessup", "Kowalczyk", "Lindqvist", "Mbeki", "Navarro", "Oyelaran", "Pruitt", "Quarles",
        "Rasmussen", "Sorensen", "Thibodeaux", "Underwood", "Vasquez", "Whitlock", "Yarbrough", "Zielinski",
        "Ashby", "Brannigan", "Coldwell", "Dumont", "Esposito", "Fontaine", "Greer", "Hargrove", "Ilunga",
        "Jovanovic", "Kincaid", "Lockhart", "Mercer", "Nakamura", "Ostrowski", "Pemberton", "Rourke", "Stavros"]
POS = [("PG", 74, 78), ("SG", 76, 79), ("SF", 78, 81), ("PF", 80, 83), ("C", 82, 86)]
SKIN = ["#F1C9A5", "#E0AC83", "#C68642", "#A86B3C", "#8D5524", "#6B3E1E", "#4A2A14"]
HAIR = ["short01", "short02", "short03", "short04", "afro01", "braid01", "ponytail01", "long01", "bob01", "none"]


def main():
    rng = random.Random(2027)
    teams = json.loads((ROOT / "data/teams.json").read_text())["teams"]
    players, used = [], set()
    for t in teams:
        numbers = rng.sample(range(0, 56), 13)
        for i in range(13):
            pos, hmin, hmax = POS[i % 5]
            while True:
                name = (rng.choice(FIRST), rng.choice(LAST))
                if name not in used:
                    used.add(name)
                    break
            height = rng.randint(hmin, hmax)
            starter = i < 5
            overall = rng.randint(76, 92) if starter else rng.randint(64, 78)
            players.append({
                "id": f"{t['id']}_{i:02d}",
                "team": t["id"],
                "first": name[0], "last": name[1],
                "number": numbers[i],
                "pos": pos,
                "height_in": height,
                "weight_lb": int(150 + (height - 70) * 7 + rng.randint(-12, 18)),
                "wingspan_in": height + rng.randint(-1, 7),
                "overall": overall,
                "starter": starter,
                "skin": rng.choice(SKIN),
                "hair": rng.choice(HAIR),
                "ratings": {k: max(25, min(99, overall + rng.randint(-14, 10))) for k in
                            ["close_shot", "mid_range", "three_point", "free_throw", "layup", "dunk",
                             "pass_accuracy", "ball_handle", "speed", "strength", "vertical", "stamina",
                             "perimeter_d", "interior_d", "steal", "block", "off_reb", "def_reb"]},
            })
    out = {"_doc": "Fictional rosters generated by tools/gen_rosters.py. Heights/wingspans in inches.",
           "players": players}
    (ROOT / "data/players.json").write_text(json.dumps(out, indent=1) + "\n")
    print(f"wrote {len(players)} players for {len(teams)} teams")


if __name__ == "__main__":
    main()
